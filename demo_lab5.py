"""Lab 5 session: directories, pathnames and symbolic links, run like a shell;
log goes to reports/lab5_output.txt."""

import shell
from shell import (
    do_cd,
    do_close,
    do_create,
    do_link,
    do_ls,
    do_mkdir,
    do_mkfs,
    do_open,
    do_read,
    do_rmdir,
    do_seek,
    do_stat,
    do_symlink,
    do_truncate,
    do_unlink,
    do_write,
    log_format,
    note,
    remount,
    save,
    section,
    show_free,
    start,
)

start()
log_format()

section("1. Formatting: the root directory has '.' and '..'")
do_mkfs(32)
do_ls()
do_stat("/")

section("2. The example from the task")
note("dir1 gets 2 hard links: 'dir1' in the CWD and '.' inside dir1.")
do_mkdir("dir1")
do_stat("dir1")
note("dir1/dir2 adds a third link to dir1: '..' inside dir2.")
do_mkdir("dir1/dir2")
do_stat("dir1")
note("The contents of the CWD, now it is /.")
do_ls()
do_stat("/")
note("A file in /dir1/dir2, reached through different pathnames and symlinks.")
do_cd("dir1/dir2")
do_create("file.txt")
do_mkdir("/a")
do_mkdir("/a/b")
do_symlink("/dir1", "/a/b/l1")
do_ls("/a/b")
fd0 = do_open("/a/b/l1/dir2/file.txt")
do_symlink("dir2/./../../dir1/././dir2/file.txt", "/dir1/l2")
do_cd("/a/b")
fd1 = do_open("l1/l2")
note("fd 0 and fd 1 are the same file: write through one, read through the other.")
do_write(fd0, b"same file")
do_read(fd1, 100)
note("Which file types unlink works on: symlinks and regular files, not directories.")
do_cd("/")
do_unlink("/dir1/l2")
do_unlink("/a/b/l1")
do_unlink("dir1/dir2/file.txt")
do_unlink("/dir1/dir2")
note("file.txt has no hard links now but is still open; closing both fds frees it.")
do_seek(fd0, 0)
do_read(fd0, 100)
do_close(fd0)
do_close(fd1)
note("More hard links can point to a symlink (link works on the symlink itself).")
do_symlink("some", "dir1/dir2/data.txt")
do_ls("dir1/dir2")
do_link("/dir1/dir2/data.txt", "/a/b/document")
do_ls("/a/b")
do_stat("/a/b/document")
do_stat("/dir1/dir2/data.txt")
note("A symlink does not have to point to an existing file.")
do_open("/dir1/dir2/data.txt")
do_create("/dir1/dir2/some")
fd = do_open("/dir1/dir2/data.txt")
do_close(fd)
note("The CWD does not have to exist.")
do_mkdir("/1")
do_mkdir("/1/2")
do_cd("/1/2")
do_rmdir("../2")
do_ls()
do_create("file.txt")
note("Its '..' was removed too, so only an absolute path leads out.")
do_cd("..")
note("Leaving the removed CWD frees its descriptor and its block.")
show_free()
do_cd("/")
show_free()
do_ls("/1")

section("3. Pathnames: absolute, relative, '.', '..', '//'")
note("'..' of the root is the root itself.")
do_stat("/..")
do_ls("/dir1/dir2/../..")
note("Empty components ('//') and '.' change nothing.")
do_stat("//dir1/./dir2//some")
note("Relative paths start at the CWD.")
do_cd("/dir1")
do_stat("dir2/some")
do_stat("../dir1/dir2/../dir2/some")
note("All Lab 4 commands take pathnames.")
fd = do_open("dir2/some")
do_write(fd, b"0123456789")
do_truncate("/dir1/dir2/some", 200)
do_link("dir2/some", "/a/copy")
do_stat("/a/copy")
do_seek(fd, 0)
do_read(fd, 12)
do_close(fd)
do_unlink("../a/copy")
note("Every component except the last one must be a directory.")
do_stat("/dir1/dir2/some/x")
do_create("/dir1/missing/x")
do_cd("/dir1/dir2/some")

section("4. Symbolic links")
do_cd("/")
note("A chain of symlinks: /s1 -> /s2 -> /dir1/dir2/some. stat shows the link itself.")
do_symlink("/s2", "/s1")
do_symlink("/dir1/dir2/some", "/s2")
do_stat("/s1")
fd = do_open("/s1")
do_read(fd, 10)
do_close(fd)
note("A relative symlink is resolved from the directory that holds it, not from the CWD.")
do_symlink("dir2/some", "/dir1/rel")
do_cd("/a")
do_stat("/dir1/rel")
fd = do_open("/dir1/rel")
do_close(fd)
note("A symlink to a directory; '..' after it goes to the real parent of the directory.")
do_cd("/")
do_symlink("/dir1/dir2", "/d")
do_cd("/d")
do_ls()
do_cd("..")
do_ls()
note("A symlink in the middle that points to a file.")
do_stat("/s1/x")
note("Symlink loops are stopped after 16 jumps.")
do_cd("/")
do_symlink("loop2", "/loop1")
do_symlink("loop1", "/loop2")
do_open("/loop1")
do_symlink("me", "/me")
do_stat("/me/x")
note("Contents up to one block (64 bytes); the contents are not checked.")
do_symlink("x" * 65, "/long")
do_symlink("y" * 64, "/max")
do_stat("/max")
note("Creating and removing a symlink does not change the links of the file it points to.")
do_stat("/dir1/dir2/some")
do_unlink("/s2")
do_stat("/dir1/dir2/some")
do_open("/s1")

section("5. Directories: link counts, mkdir, rmdir")
do_stat("/a")
do_mkdir("/a/c")
do_stat("/a")
note("Errors: hard link to a directory, rmdir of a non-empty or wrong target.")
do_link("/a", "/a2")
do_rmdir("/a")
do_rmdir("/dir1/dir2/some")
do_rmdir("/d")
do_rmdir("/")
do_rmdir("/a/c/.")
do_rmdir("/a/c/..")
do_mkdir("/a/c")
do_mkdir("/a/bad/name/")
note("rmdir gives back the descriptor, the block, and the parent's link.")
show_free()
do_rmdir("/a/c")
do_stat("/a")
show_free()

section("6. Unmount and mount again: the tree is still there")
remount()
do_ls("/")
do_ls("/a/b")
do_stat("/a/b/document")
fd = do_open("/dir1/rel")
do_read(fd, 10)
do_close(fd)

shell.k.unmount()
save("lab5_output.txt")
